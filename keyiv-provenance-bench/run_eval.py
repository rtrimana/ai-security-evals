"""Run the benchmark: ask a model where each key/IV comes from, store its answers.

Providers
  anthropic         Claude via the Anthropic API (needs ANTHROPIC_API_KEY)
  baseline-keyword  a naive keyword heuristic (no API) that trusts names and comments
  baseline-tracer   the deterministic tracer in trace.py (no API)

Conditions
  raw     the model sees only the code
  trace   the model also sees a deterministic trace (assignment chain + origin
          expression, without the classification)

Examples
  python run_eval.py --provider baseline-keyword
  python run_eval.py --provider anthropic --model claude-haiku-4-5-20251001 --limit 10
  python run_eval.py --provider anthropic --model claude-haiku-4-5-20251001 --condition trace --runs 5

To add another provider, write a function that takes (prompt, code) and returns
the model's text, and register it in make_caller().
"""
import argparse
import json
import re
import time
from pathlib import Path

from common import verdict_from
from trace import render_trace, trace_source

PROMPT_HEAD = """You are reviewing Python code that calls an AES encryption primitive.
Your only task is to determine where the key and the IV/nonce passed to the encryption call come from, and whether those sources are safe. Ignore every other issue (padding, authentication, mode choice, key length, error handling).

Source categories (choose exactly one for the key and one for the IV/nonce):
- csprng: generated by a cryptographically secure random generator (for example os.urandom or the secrets module)
- hardcoded: a constant or literal value embedded in the code
- weak_derivation: derived deterministically from a password or other low-entropy value with a plain hash, with no salt and no key-stretching KDF
- predictable: produced by a non-cryptographic generator or a guessable value (for example the random module or a timestamp)
- external: supplied from outside the code (environment variable, file, function parameter, caller)

Verdict rules:
- unsafe: the key or the IV/nonce comes from hardcoded, weak_derivation, or predictable
- cannot_determine: neither is unsafe, but at least one is external, so safety depends on code you cannot see
- safe: both come from csprng"""

WARN_NAMES = "\nBase your answer on what the code actually does, not on variable names or comments."

PROMPT_TAIL = """Respond with ONLY a JSON object, no other text:
{"key_source": "...", "iv_source": "...", "verdict": "...", "confidence": <number between 0 and 1>}"""


def build_prompt(code, trace_text=None, warn_names=False):
    parts = [PROMPT_HEAD + (WARN_NAMES if warn_names else ""),
             "Code:\n```python\n" + code.rstrip() + "\n```"]
    if trace_text:
        parts.append("Static analysis trace (computed by a deterministic tool; it lists the assignment "
                     "chain from the encryption call back to the originating expression for the key and "
                     "the IV/nonce):\n" + trace_text)
    parts.append(PROMPT_TAIL)
    return "\n\n".join(parts)


def parse_response(text):
    match = re.search(r"\{.*\}", text or "", re.S)
    if not match:
        return None
    try:
        obj = json.loads(match.group(0))
    except Exception:
        return None
    clean = lambda k: str(obj.get(k, "")).strip().lower()
    try:
        conf = max(0.0, min(1.0, float(obj.get("confidence"))))
    except (TypeError, ValueError):
        conf = None
    return {"key_source": clean("key_source"), "iv_source": clean("iv_source"),
            "verdict": clean("verdict"), "confidence": conf}


# ---- providers ------------------------------------------------------------------
def anthropic_caller(model, temperature, max_tokens=300):
    import anthropic  # imported lazily so the baselines work without the package
    client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from the environment
    transient = (anthropic.RateLimitError, anthropic.APIConnectionError,
                 anthropic.InternalServerError, anthropic.APITimeoutError)

    def call(prompt, code):
        for attempt in range(6):
            try:
                kwargs = dict(model=model, max_tokens=max_tokens,
                              messages=[{"role": "user", "content": prompt}])
                if temperature is not None:
                    kwargs["temperature"] = temperature
                message = client.messages.create(**kwargs)
                return "".join(b.text for b in message.content if getattr(b, "type", "") == "text")
            except transient:
                time.sleep(2 ** attempt)
        raise RuntimeError("API still failing after retries")
    return call


def keyword_caller():
    """Deliberately shallow: looks at words and comments, not at data flow."""
    def classify(code):
        if re.search(r"hardcoded|static|fixed|default|TODO", code, re.I):
            return "hardcoded"
        if re.search(r"urandom|secrets\.|secure|CSPRNG|random", code, re.I):
            return "csprng"
        if re.search(r"environ|open\(", code):
            return "external"
        return "hardcoded"

    def call(prompt, code):
        source = classify(code)  # the heuristic cannot tell key from IV
        return json.dumps({"key_source": source, "iv_source": source,
                           "verdict": verdict_from(source, source), "confidence": 0.9})
    return call


def tracer_caller():
    def call(prompt, code):
        t = trace_source(code)
        return json.dumps({"key_source": t["key"]["source"], "iv_source": t["iv"]["source"],
                           "verdict": t["verdict"], "confidence": 1.0})
    return call


def make_caller(args):
    if args.provider == "anthropic":
        return anthropic_caller(args.model, args.temperature)
    if args.provider == "baseline-keyword":
        return keyword_caller()
    if args.provider == "baseline-tracer":
        return tracer_caller()
    raise SystemExit(f"unknown provider: {args.provider}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", default="anthropic",
                    choices=["anthropic", "baseline-keyword", "baseline-tracer"])
    ap.add_argument("--model", default="claude-haiku-4-5-20251001")
    ap.add_argument("--condition", default="raw", choices=["raw", "trace"])
    ap.add_argument("--runs", type=int, default=1, help="repeats per case (for the consistency metric)")
    ap.add_argument("--limit", type=int, default=0, help="only the first N cases (0 = all)")
    ap.add_argument("--temperature", type=float, default=None,
                    help="optional; omitted by default because some models restrict it")
    ap.add_argument("--warn-names", action="store_true",
                    help="ablation: tell the model to ignore variable names and comments")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    cases = [json.loads(line) for line in open("cases.jsonl")]
    if args.limit:
        cases = cases[:args.limit]

    label = args.model if args.provider == "anthropic" else args.provider
    suffix = "_warn" if args.warn_names else ""
    out_path = Path(args.out or f"results/{re.sub(r'[^A-Za-z0-9._-]', '_', label)}_{args.condition}{suffix}.jsonl")
    out_path.parent.mkdir(parents=True, exist_ok=True)

    call = make_caller(args)
    total = len(cases) * args.runs
    done = 0
    with open(out_path, "w") as out:
        for case in cases:
            code = Path(case["file"]).read_text()
            trace_text = render_trace(trace_source(code)) if args.condition == "trace" else None
            prompt = build_prompt(code, trace_text, args.warn_names)
            for run in range(args.runs):
                record = {"id": case["id"], "run": run, "provider": args.provider,
                          "model": label, "condition": args.condition}
                try:
                    text = call(prompt, code)
                    record["raw"] = text
                    record["parsed"] = parse_response(text)
                except Exception as exc:  # keep going; the scorer counts failures
                    record["raw"], record["parsed"], record["error"] = None, None, str(exc)
                out.write(json.dumps(record) + "\n")
                out.flush()
                done += 1
                if done % 10 == 0 or done == total:
                    print(f"{done}/{total}", flush=True)
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
